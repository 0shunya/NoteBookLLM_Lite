from app.services.citation_validator import validate_citations
from app.services.source_builder import Source


def create_test_sources() -> list[Source]:
    """
    Create a small set of fake sources for validator testing.
    """

    return [
        Source(
            source_id=1,
            chunk_id=101,
            document_id="demo-document",
            filename="resume.pdf",
            page_number=1,
            text="Python and JavaScript are listed as skills.",
            distance=0.2,
        ),
        Source(
            source_id=2,
            chunk_id=102,
            document_id="demo-document",
            filename="resume.pdf",
            page_number=2,
            text="The candidate has experience with React.",
            distance=0.3,
        ),
    ]


def run_test(name: str, answer: str):
    """
    Run one validation scenario and print the result.
    """

    sources = create_test_sources()

    validation = validate_citations(
        answer=answer,
        sources=sources,
    )

    print(f"\n===== {name} =====\n")
    print("ANSWER:")
    print(answer)

    print("\nVALIDATION:")
    print(f"Valid: {validation['valid']}")
    print(
        f"Cited source IDs: "
        f"{validation['cited_source_ids']}"
    )
    print(
        f"Invalid source IDs: "
        f"{validation['invalid_source_ids']}"
    )
    print(
        f"Uncited sentences: "
        f"{validation['uncited_sentences']}"
    )


def main():

    # ---------------------------------------------------------------
    # TEST 1
    # Citation before punctuation
    # ---------------------------------------------------------------

    run_test(
        "TEST 1 — Citation Before Period",
        "The candidate knows Python [1].",
    )

    # ---------------------------------------------------------------
    # TEST 2
    # Citation after punctuation.
    #
    # This is the exact format generated by our LLM.
    # ---------------------------------------------------------------

    run_test(
        "TEST 2 — Citation After Period",
        "The candidate knows Python. [1]",
    )

    # ---------------------------------------------------------------
    # TEST 3
    # Invalid citation ID
    # ---------------------------------------------------------------

    run_test(
        "TEST 3 — Invalid Citation ID",
        "The candidate knows Rust [99].",
    )

    # ---------------------------------------------------------------
    # TEST 4
    # Missing citation
    # ---------------------------------------------------------------

    run_test(
        "TEST 4 — Missing Citation",
        "The candidate knows Python.",
    )

    # ---------------------------------------------------------------
    # TEST 5
    # Valid sentence followed by uncited sentence
    # ---------------------------------------------------------------

    run_test(
        "TEST 5 — Mixed Valid and Uncited Claims",
        (
            "The candidate knows Python [1]. "
            "The candidate has ten years of Rust experience."
        ),
    )

    # ---------------------------------------------------------------
    # TEST 6
    # Multiple valid citations
    # ---------------------------------------------------------------

    run_test(
        "TEST 6 — Multiple Valid Citations",
        (
            "The candidate knows Python [1]. "
            "The candidate also knows React [2]."
        ),
    )


if __name__ == "__main__":
    main()