from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db.models import Chunk, Embedding
from app.services.embedding_service import (
    EMBEDDING_MODEL,
    generate_embedding,
)


def embed_document_chunks(
    db: Session,
    document_id: str,
) -> int:
    """
    Generate and store embeddings for every chunk belonging
    to a document.

    Existing embeddings for the same chunk and model are reused.
    This makes the operation safe to run more than once.
    """

    # ---------------------------------------------------------
    # 1. Get all chunks belonging to the document
    # ---------------------------------------------------------

    chunks = db.scalars(
        select(Chunk)
        .where(Chunk.document_id == document_id)
        .order_by(Chunk.id)
    ).all()

    if not chunks:
        return 0

    embedded_count = 0

    # ---------------------------------------------------------
    # 2. Generate an embedding for each chunk
    # ---------------------------------------------------------

    for chunk in chunks:

        # Check whether this chunk already has an embedding
        # generated by our current embedding model.
        existing_embedding = db.scalar(
            select(Embedding)
            .where(
                Embedding.chunk_id == chunk.id,
                Embedding.model == EMBEDDING_MODEL,
            )
        )

        # Don't generate the same embedding twice.
        if existing_embedding:
            continue

        vector = generate_embedding(chunk.text)

        embedding = Embedding(
            chunk_id=chunk.id,
            model=EMBEDDING_MODEL,
            embedding=vector,
        )

        db.add(embedding)

        embedded_count += 1

    # ---------------------------------------------------------
    # 3. Save all embeddings atomically
    # ---------------------------------------------------------

    db.commit()

    return embedded_count